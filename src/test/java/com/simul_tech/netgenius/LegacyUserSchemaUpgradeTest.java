package com.simul_tech.netgenius;

import com.simul_tech.netgenius.models.User;
import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.List;
import java.util.Properties;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class LegacyUserSchemaUpgradeTest {

    @Test
    void hibernateUpdateAddsRoleToPopulatedLegacyTableWithoutChangingCredentials() throws SQLException {
        String jdbcUrl = databaseUrl();
        try (Connection connection = DriverManager.getConnection(jdbcUrl, "sa", "")) {
            JdbcTemplate jdbc = legacyUsers(connection);
            addUser(jdbc, "student@example.test", "existing-password-hash-1");
            addUser(jdbc, "teacher@example.test", "existing-password-hash-2");
            jdbc.update("UPDATE users SET enabled = false WHERE email = ?", "student@example.test");

            Properties settings = new Properties();
            settings.setProperty("hibernate.connection.url", jdbcUrl);
            settings.setProperty("hibernate.connection.username", "sa");
            settings.setProperty("hibernate.connection.password", "");
            settings.setProperty("hibernate.hbm2ddl.auto", "update");
            settings.setProperty("hibernate.hbm2ddl.halt_on_error", "true");
            try (SessionFactory ignored = new Configuration()
                    .addAnnotatedClass(User.class)
                    .setProperties(settings)
                    .buildSessionFactory()) {
                assertThat(users(jdbc)).containsExactly(
                        new StoredUser("student@example.test", "existing-password-hash-1", false, "USER"),
                        new StoredUser("teacher@example.test", "existing-password-hash-2", true, "USER"));
                assertRoleDefaultAndNotNull(jdbc);
            }
        }
    }

    @Test
    void manualUpgradeAddsRoleAndCanBeRepeatedWithoutChangingLegacyUsers() throws SQLException {
        try (Connection connection = DriverManager.getConnection(databaseUrl(), "sa", "")) {
            JdbcTemplate jdbc = legacyUsers(connection);
            addUser(jdbc, "student@example.test", "existing-password-hash");

            runUpgrade(connection);
            List<StoredUser> upgraded = users(jdbc);
            assertThat(upgraded).containsExactly(
                    new StoredUser("student@example.test", "existing-password-hash", true, "USER"));

            runUpgrade(connection);
            assertThat(users(jdbc)).isEqualTo(upgraded);
            assertRoleDefaultAndNotNull(jdbc);
        }
    }

    @Test
    void manualUpgradePreservesAssignedRolesAndOnlyFillsNullRoles() throws SQLException {
        try (Connection connection = DriverManager.getConnection(databaseUrl(), "sa", "")) {
            JdbcTemplate jdbc = legacyUsers(connection);
            jdbc.execute("ALTER TABLE users ADD COLUMN role varchar(20)");
            for (String role : new String[]{"USER", "STUDENT", "TEACHER", "ADMIN"}) {
                String email = role.toLowerCase() + "@example.test";
                addUser(jdbc, email, "existing-" + role + "-password-hash");
                jdbc.update("UPDATE users SET role = ? WHERE email = ?", role, email);
            }
            addUser(jdbc, "unassigned@example.test", "existing-unassigned-password-hash");
            List<StoredUser> expected = users(jdbc).stream()
                    .map(user -> user.role() == null
                            ? new StoredUser(user.email(), user.password(), user.enabled(), "USER") : user)
                    .toList();

            runUpgrade(connection);
            runUpgrade(connection);

            assertThat(users(jdbc)).isEqualTo(expected);
            assertRoleDefaultAndNotNull(jdbc);
        }
    }

    private static String databaseUrl() {
        return "jdbc:h2:mem:legacy-users-" + UUID.randomUUID() + ";MODE=PostgreSQL";
    }

    private static JdbcTemplate legacyUsers(Connection connection) {
        JdbcTemplate jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
        jdbc.execute("""
                CREATE TABLE users (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at timestamp,
                    email varchar(255) NOT NULL UNIQUE,
                    enabled boolean NOT NULL,
                    first_name varchar(255) NOT NULL,
                    last_name varchar(255) NOT NULL,
                    middle_name varchar(255),
                    password varchar(255) NOT NULL,
                    updated_at timestamp
                )
                """);
        return jdbc;
    }

    private static void addUser(JdbcTemplate jdbc, String email, String password) {
        jdbc.update("""
                INSERT INTO users (email, password, enabled, first_name, last_name)
                VALUES (?, ?, true, 'Existing', 'User')
                """, email, password);
    }

    private static List<StoredUser> users(JdbcTemplate jdbc) {
        return jdbc.query("SELECT email, password, enabled, role FROM users ORDER BY id",
                (rs, row) -> new StoredUser(rs.getString("email"), rs.getString("password"),
                        rs.getBoolean("enabled"), rs.getString("role")));
    }

    private static void runUpgrade(Connection connection) {
        ScriptUtils.executeSqlScript(connection, new FileSystemResource("deploy/upgrade-legacy-users.sql"));
    }

    private static void assertRoleDefaultAndNotNull(JdbcTemplate jdbc) {
        addUser(jdbc, "new-user@example.test", "new-password-hash");
        assertThat(jdbc.queryForObject("SELECT role FROM users WHERE email = ?", String.class,
                "new-user@example.test")).isEqualTo("USER");
        assertThatThrownBy(() -> jdbc.update("UPDATE users SET role = NULL WHERE email = ?",
                "new-user@example.test")).isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
    }

    private record StoredUser(String email, String password, boolean enabled, String role) {
    }
}
